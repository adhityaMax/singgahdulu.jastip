CREATE POLICY profiles_read ON public.profiles FOR SELECT TO authenticated
USING (id = (SELECT auth.uid()) OR public.current_app_role() = 'admin');

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['settings','batches','orders','expenses','settlements'] LOOP
    EXECUTE format('CREATE POLICY member_read ON public.%I FOR SELECT TO authenticated USING (public.current_app_role() IN (''admin'', ''koordinator'', ''driver''))', t);
  END LOOP;
  FOREACH t IN ARRAY ARRAY['batches','orders','expenses'] LOOP
    EXECUTE format('CREATE POLICY operator_write ON public.%I FOR ALL TO authenticated USING (public.current_app_role() IN (''admin'', ''koordinator'')) WITH CHECK (public.current_app_role() IN (''admin'', ''koordinator''))', t);
  END LOOP;
END $$;
CREATE POLICY admin_settings ON public.settings FOR ALL TO authenticated
USING (public.current_app_role() = 'admin') WITH CHECK (public.current_app_role() = 'admin');
CREATE POLICY operator_settlements ON public.settlements FOR INSERT TO authenticated
WITH CHECK (public.current_app_role() IN ('admin','koordinator') AND created_by = (SELECT auth.uid()));

