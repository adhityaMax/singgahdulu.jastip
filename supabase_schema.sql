-- 2. TABEL BATCHES
CREATE TABLE IF NOT EXISTS public.batches (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    route TEXT NOT NULL,
    cutoff_date DATE,
    arrival_date DATE,
    status TEXT NOT NULL DEFAULT 'ACTIVE',
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);




-- 3. TABEL ORDERS
CREATE TABLE IF NOT EXISTS public.orders (
    id TEXT PRIMARY KEY,
    batch_id TEXT REFERENCES public.batches(id) ON DELETE CASCADE,
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    customer TEXT NOT NULL,
    phone TEXT,
    item TEXT NOT NULL,
    store TEXT NOT NULL,
    price NUMERIC NOT NULL DEFAULT 0,
    fee NUMERIC NOT NULL DEFAULT 0,
    qty INT NOT NULL DEFAULT 1,
    pay_status TEXT NOT NULL DEFAULT 'LUNAS',
    dp_amount NUMERIC DEFAULT 0,
    item_status TEXT NOT NULL DEFAULT 'PENDING',
    buyer TEXT NOT NULL DEFAULT 'Umay',
    pickup TEXT NOT NULL DEFAULT 'Self Pick-up',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);




-- 4. TABEL EXPENSES
CREATE TABLE IF NOT EXISTS public.expenses (
    id TEXT PRIMARY KEY,
    batch_id TEXT REFERENCES public.batches(id) ON DELETE CASCADE,
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    category TEXT NOT NULL,
    amount NUMERIC NOT NULL DEFAULT 0,
    note TEXT,
    paid_by TEXT NOT NULL DEFAULT 'Adhit',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);




-- 5. ROW LEVEL SECURITY (RLS)
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.batches ENABLE ROW LEVEL SECURITY;
